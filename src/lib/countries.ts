/**
 * Resolve a country input — an ISO code ("PH"), a code with region ("US-CA"),
 * or a full name — to a display name from our list. Returns undefined when
 * the input can't be matched.
 */
export function resolveCountryName(input?: string | null): string | undefined {
  if (!input) return undefined;
  const trimmed = input.trim();
  if (!trimmed) return undefined;

  // Exact name match (case-insensitive).
  const lower = trimmed.toLowerCase();
  const byName = countries.find((c) => c.name.toLowerCase() === lower);
  if (byName) return byName.name;

  // ISO code (or region-prefixed code such as "US-CA").
  const code = trimmed.slice(0, 2).toUpperCase();
  return countryByCode.get(code);
}

