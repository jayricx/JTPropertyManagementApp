/**
 * Best-effort country from the runtime's time zone. Used when the server
 * couldn't provide the IP-based country (e.g. local development).
 */
export function guessCountryFromTimeZone(
  timeZone?: string | null,
): string | undefined {
  if (!timeZone) return undefined;
  const code = timeZoneCountries[timeZone];
  return code ? resolveCountryName(code) : undefined;
}
